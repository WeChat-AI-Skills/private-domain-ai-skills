#!/usr/bin/env python3
"""Build human-readable domain pages from the installed catalog; --check never writes."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / ".agents/skills/private-domain-ops/references/catalog/skill-tree.json"
COVERAGE = {"covered": "已有方法/脚本", "partial": "部分覆盖", "planned": "待建设"}


def outputs(root=ROOT):
    catalog = json.loads((root / CATALOG.relative_to(ROOT)).read_text())
    roles = json.loads((root / ".agents/skills/private-domain-ops/references/catalog/agent-registry.json").read_text())
    role_labels = {r["id"]: r["label"] for r in roles["agents"]}
    header = "<!-- Generated by scripts/build_catalog_docs.py; edit the installed skill-tree.json. -->\n\n"
    result = {}
    overview = [header + "# 技能树总览", "", f"v{catalog['package_version']} · 七类能力 · 28 个节点 · 15 项可安装技能。", "",
                "以客户需求、意图与体验为中心。下表描述方法覆盖，真实可用范围取决于客户环境；商品上架等待建设节点不属于当前已交付执行能力。", "",
                "[安装与首次使用](quickstart.md) · [角色与系统架构](architecture.md) · [当前验证范围](capability-status.md)", "",
                "| 七类能力 | 主要职责 | 节点 |", "| --- | --- | --- |"]
    for domain in catalog["domains"]:
        filename = f"{domain['order']:02}-{domain['id']}.md"
        overview.append(f"| [{domain['label']}](domains/{filename}) | {domain['purpose']} | 4 |")
        rows = [header + f"# {domain['order']:02} {domain['label']}", "", domain["purpose"], "",
                f"主责角色：[{role_labels[domain['owner_agent']]}](../../.agents/skills/private-domain-ops/references/agents/{domain['owner_agent']}.md)。", "",
                f"需要资料：{domain['inputs']}。", "", "可以对自己的 Agent 说：", "", "> " + domain["example_prompt"], "",
                "| 节点 | 能力 | 当前方法覆盖 | 可复用技能 | 结果要求与缺口 |", "| --- | --- | --- | --- | --- |"]
        for node in catalog["nodes"]:
            if node["domain_id"] != domain["id"]:
                continue
            links = "、".join(f"[{s}](../../.agents/skills/{s}/SKILL.md)" for s in node["skill_refs"]) or "尚无对应技能包"
            rows.append(f"| {node['id']} | {node['label']} | {COVERAGE[node['method_coverage']]} | {links} | {node['acceptance']}；{node['gap']} |")
        rows += ["", "上表的“已有方法/脚本”不等于客户现场已接入。外部工具能力按企业、工作号与动作单独验证，当前目录所有节点现场状态均为未验证。", "",
                 "[返回技能树](../skill-tree-overview.md) · [开始使用](../quickstart.md) · [能力状态](../capability-status.md)"]
        result[f"docs/domains/{filename}"] = "\n".join(rows) + "\n"
    overview += ["", "## 安装包映射", "", "每项技能保留原名称与平铺安装路径。公共技能可以跨域复用；主责角色不限制其他角色按任务使用。", "",
                 "| 技能 | 主业务域 | 主责角色 |", "| --- | --- | --- |"]
    labels = {d["id"]: d["label"] for d in catalog["domains"]}
    for skill in catalog["skills"]:
        suffix = "（扩展维护）" if skill["visibility"] == "extension" else ""
        overview.append(f"| [{skill['id']}](../.agents/skills/{skill['id']}/SKILL.md){suffix} | {labels[skill['primary_domain']]} | {role_labels[skill['owner_agent']]} |")
    overview += ["", "机器入口：[技能树目录](../.agents/skills/private-domain-ops/references/catalog/skill-tree.json)。manifest.json 保留安装清单及旧六域字段；产品导航以本目录为准。"]
    result["docs/skill-tree-overview.md"] = "\n".join(overview) + "\n"
    result["assets/skill-tree-content.json"] = json.dumps({"package_version": catalog["package_version"], "title": "私域 AI 技能树", "domains": [
        {"id": d["id"], "label": d["label"], "nodes": [{"id": n["id"], "label": n["label"]} for n in catalog["nodes"] if n["domain_id"] == d["id"]]} for d in catalog["domains"]
    ], "roles": [{"id": r["id"], "label": r["label"], "reports_to": r["reports_to"]} for r in roles["agents"]]}, ensure_ascii=False, indent=2) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, body in outputs().items():
        dest = ROOT / path
        if args.check:
            if not dest.is_file() or dest.read_text() != body:
                stale.append(path)
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(body)
    print("Generated catalog is current" if args.check and not stale else ("Stale: " + ", ".join(stale) if stale else "Generated catalog documents"))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
